// --- Learn: every lesson, its guided swaps and free swaps, to "Lesson complete".
{
  const lines = [...header('Learn: the six lessons, each guided swap played on the board cursor, Next lesson between them.'),
    'until 600 Jewel Cascade', 'frames 30', 'click =Play', 'until 120 Choose a mode', 'frames 10',
    'click =Learn. Short hands-on lessons — one rule at a time.', 'until 120 Setup', 'frames 10'];
  content.LESSONS.forEach((lesson, li) => {
    if (li === 0) lines.push(`click ${lesson.name.split(' — ')[0]} —`, 'frames 10', 'click =Start');
    lines.push('until 600 =Lesson', 'frames 10');
    if (li === 0) lines.push('save lesson-1');
    const state = rules.createGame(lesson.toEngineConfig());
    const cur = { active: false, x: -1, y: -1 };
    let crates = 0;
    lesson.steps.forEach((s, si) => {
      const last = si === lesson.steps.length - 1;
      // Play until this step's requirement is met (guided swaps exactly; others by the hint).
      for (let guard = 0; guard < 12; guard++) {
        const mv = s.require && s.require.kind === 'swap' ? { ax: s.require.ax, ay: s.require.ay, bx: s.require.bx, by: s.require.by } : rules.suggestMove(state);
        const before = rules.cloneState(state);
        const res = rules.applyCommand(state, { id: `l${li}-${si}-${guard}`, type: 'swap', ...mv });
        if (!res.accepted) throw new Error(`lesson ${li + 1} step ${si + 1}: ${res.reason}`);
        const ev = res.events;
        const r = s.require || { kind: 'any-swap' };
        let hit;
        if (r.kind === 'swap' || r.kind === 'any-swap') hit = true;
        else if (r.kind === 'create') hit = ev.some((e) => e.t === 'create' && (!r.s || r.s.includes(e.s)));
        else if (r.kind === 'break-ice') hit = ev.some((e) => e.t === 'crack' && e.ice === 0);
        else if (r.kind === 'break-crate') { crates += ev.filter((e) => e.t === 'crate-break').length; hit = crates >= (r.n || 1); }
        else hit = true;
        const done = hit && last;
        lines.push(...swapSteps(before, cur, mv, 'Lesson', done || state.phase !== 'ready'));
        if (hit) break;
        if (state.phase !== 'ready') throw new Error(`lesson ${li + 1} ended early`);
      }
    });
    lines.push('frames 30', 'expect Commission complete!');
    if (li === 0) lines.push('save lesson-results');
    if (li < content.LESSONS.length - 1) lines.push('click =Next lesson');
  });
  lines.push('click =Mode select', 'until 120 Choose a mode');
  write('learn-lessons.play', lines);
}

