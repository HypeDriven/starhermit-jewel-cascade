// Writes the engine play scripts in tests/native/ from the rules: each round is
// simulated here with js/engine/rules.js (the same deterministic code the game
// runs), the moves chosen by the rules' own hint (suggestMove) or by a lesson's
// guided swaps, and turned into keyboard steps for the board cursor
// (native/render.ts cursorMove: arrows wrap round the board and skip holes;
// Enter selects, Enter on a neighbour swaps). Each swap waits for the HUD to
// read "Your move" (or "Lesson") again before the next, so timing never drifts.
// Run: node tools/gen-plays.mjs   (npm run plays)
import { writeFileSync, mkdirSync } from 'node:fs';
import * as rules from '../js/engine/rules.js';
import * as content from '../js/engine/content.js';

const OUT = new URL('../tests/native/', import.meta.url);
mkdirSync(OUT, { recursive: true });

/** Cursor model (render.ts): inactive until the first key; arrows wrap and skip holes. */
function cursorKeys(state, cur, tx, ty) {
  const w = state.width, h = state.height;
  const playable = (x, y) => state.cells[y * w + x].play;
  const move = (x, y, dx, dy) => {
    for (let step = 0; step < Math.max(w, h); step++) {
      x = (x + dx + w) % w; y = (y + dy + h) % h;
      if (playable(x, y)) break;
    }
    return [x, y];
  };
  const DIRS = [['ArrowUp', 0, -1], ['ArrowDown', 0, 1], ['ArrowLeft', -1, 0], ['ArrowRight', 1, 0]];
  let start = cur.active ? [cur.x, cur.y] : null;
  if (!start) {
    let first = null;
    for (let y = 0; y < h && !first; y++) for (let x = 0; x < w; x++) if (playable(x, y)) { first = [x, y]; break; }
    // The first Enter (or arrow) shows the cursor on the first playable cell.
    cur.active = true; cur.x = first[0]; cur.y = first[1];
    start = first;
    if (start[0] === tx && start[1] === ty) return [];
  }
  // Breadth-first over arrow presses.
  const key = (p) => p[0] + ',' + p[1];
  const prev = new Map([[key(start), null]]);
  const queue = [start];
  while (queue.length) {
    const p = queue.shift();
    if (p[0] === tx && p[1] === ty) break;
    for (const [k, dx, dy] of DIRS) {
      const n = move(p[0], p[1], dx, dy);
      if (!prev.has(key(n))) { prev.set(key(n), [p, k]); queue.push(n); }
    }
  }
  const keys = [];
  for (let p = [tx, ty]; prev.get(key(p)); p = prev.get(key(p))[0]) keys.unshift(prev.get(key(p))[1]);
  cur.x = tx; cur.y = ty;
  return keys;
}

/** Steps for one swap a→b, then the wait for the board to settle on `ready`. */
function swapSteps(state, cur, mv, ready, last) {
  const out = [];
  const keysA = cursorKeys(state, cur, mv.ax, mv.ay);
  if (!keysA.length && out.length === 0) { /* already there (or first show) */ }
  for (const k of keysA) out.push(`key ${k} 1`, 'frames 1');
  out.push('key Enter 1', 'frames 2');
  for (const k of cursorKeys(state, cur, mv.bx, mv.by)) out.push(`key ${k} 1`, 'frames 1');
  out.push('key Enter 1', 'frames 8');
  out.push(last ? 'until 1500 Score breakdown' : `until 1500 =${ready}`, 'frames 4');
  return out;
}

/** Plays a content descriptor with the hint bot; returns the steps and the final state. */
function botRound(c, maxMoves = 60) {
  const state = rules.createGame(c.toEngineConfig());
  const cur = { active: false, x: -1, y: -1 };
  const out = [];
  let n = 0;
  while (state.phase === 'ready' && n < maxMoves) {
    const mv = rules.suggestMove(state);
    if (!mv) break;
    const before = rules.cloneState(state);
    const res = rules.applyCommand(state, { id: 'g' + n++, type: 'swap', ...mv });
    if (!res.accepted) throw new Error('bot move refused: ' + res.reason);
    out.push(...swapSteps(before, cur, mv, 'Your move', state.phase !== 'ready'));
  }
  return { out, state, moves: n };
}

const header = (title) => [`# Generated by tools/gen-plays.mjs: ${title}`];
const write = (name, lines) => writeFileSync(new URL(name, OUT), lines.join('\n') + '\n');

